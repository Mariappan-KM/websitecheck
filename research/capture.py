"""Capture visual evidence for the dashboard (public pages only).

For each Indian site in findings.json (+ manual seeds):
  - live screenshot of the infected page           -> preview/evidence/<domain>-live.jpg
  - Wayback screenshot of the last clean copy       -> preview/evidence/<domain>-before.jpg
  - live response headers as browser and Googlebot  -> preview/evidence.js (window.EVIDENCE)
"""
import asyncio, json, os, pathlib, re, urllib.request, ssl
from datetime import date
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT.parent / "preview" / "evidence"
BROWSER = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
GOOGLEBOT = "Mozilla/5.0 (compatible; Googlebot/2.1; +http://www.google.com/bot.html)"
KEEP = ("server", "x-powered-by", "content-type", "location", "cf-cache-status", "x-litespeed-cache", "x-redirect-by", "via")
CTX = ssl.create_default_context(); CTX.check_hostname = False; CTX.verify_mode = ssl.CERT_NONE

SEEDS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "seeds.json"))) if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "seeds.json")) else []   # optional local hand-picked sites

def headers(url, ua):
    req = urllib.request.Request(url, headers={"User-Agent": ua}, method="GET")
    try:
        with urllib.request.urlopen(req, timeout=25, context=CTX) as r:
            h = {k.lower(): v for k, v in r.headers.items()}
            st = r.status
    except urllib.error.HTTPError as e:
        h = {k.lower(): v for k, v in (e.headers or {}).items()}; st = e.code
    except Exception as e:
        return {"status": 0, "error": type(e).__name__}
    out = {"status": st}
    for k in KEEP:
        if k in h: out[k] = h[k]
    return out

def targets():
    F = json.load(open(ROOT / "findings.json", encoding="utf-8"))
    t = [{"domain": r["domain"], "page_url": r["page_url"],
          "last_clean": r.get("last_clean") or (r.get("home_history") or {}).get("last_clean"),
          "home_history": bool(not r.get("last_clean") and (r.get("home_history") or {}).get("last_clean"))}
         for r in F if r.get("india")]
    return SEEDS + [x for x in t if x["domain"] not in {s["domain"] for s in SEEDS}]

async def shot(page, url, path):
    try:
        await page.goto(url, timeout=45000, wait_until="domcontentloaded")
        await page.wait_for_timeout(2500)
        await page.screenshot(path=str(path), type="jpeg", quality=60, clip={"x": 0, "y": 0, "width": 1280, "height": 800})
        return True
    except Exception:
        return False

async def main():
    OUT.mkdir(parents=True, exist_ok=True)
    ev = {}
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={"width": 1280, "height": 800}, user_agent=BROWSER, ignore_https_errors=True, accept_downloads=False)
        page = await ctx.new_page()
        for t in targets():
            d = t["domain"]; e = {"captured": date.today().isoformat(), "page_url": t["page_url"]}
            if await shot(page, t["page_url"], OUT / f"{d}-live.jpg"): e["live"] = f"evidence/{d}-live.jpg"
            if t["last_clean"]:
                target = f"https://{d}/" if t.get("home_history") else t["page_url"]
                if await shot(page, f"https://web.archive.org/web/{t['last_clean']}if_/{target}", OUT / f"{d}-before.jpg"):
                    e["before"] = f"evidence/{d}-before.jpg"; e["before_ts"] = t["last_clean"][:8]
            e["headers"] = {"browser": headers(t["page_url"], BROWSER), "googlebot": headers(t["page_url"], GOOGLEBOT)}
            ev[d] = e
            print(f"{d:<30} live={'live' in e} before={'before' in e} status={e['headers']['browser'].get('status')}", flush=True)
        await b.close()
    (ROOT.parent / "preview" / "evidence.js").write_text(
        "// generated by research/capture.py on " + date.today().isoformat() + "\nwindow.EVIDENCE = " + json.dumps(ev, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    print("wrote preview/evidence.js with", len(ev), "sites")

if __name__ == "__main__":
    asyncio.run(main())
