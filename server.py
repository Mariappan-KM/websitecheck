"""SiteWatch India — local server (no extra packages).

    python server.py            -> http://127.0.0.1:8790

Serves the dashboard in preview/ and three local endpoints the dashboard uses:
    GET  /api/defaults   default search values (latest Common Crawl month etc.)
    POST /api/search     start a search run (one at a time)
    GET  /api/status     progress of the current / last run
Only listens on 127.0.0.1, so only this computer can reach it.
"""
import json, os, re, subprocess, sys, threading, time, urllib.request
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler

ROOT = os.path.dirname(os.path.abspath(__file__))
PREVIEW = os.path.join(ROOT, "preview")
RESEARCH = os.path.join(ROOT, "research")
HOST, PORT = "127.0.0.1", int(os.environ.get("SITEWATCH_PORT", "8790"))
LANG_CHOICES = {"ind": "Indonesian", "tha": "Thai", "vie": "Vietnamese", "msa": "Malay", "jpn": "Japanese", "zho": "Chinese"}

state_lock = threading.Lock()
status = {"running": False, "step": "", "steps": [], "done": 0, "total": 0, "log": [], "started": None, "finished": None,
          "error": None, "params": None, "summary": None}
_latest_crawl = {"id": None, "at": 0}

def latest_crawl():
    if _latest_crawl["id"] and time.time() - _latest_crawl["at"] < 6 * 3600:
        return _latest_crawl["id"]
    try:
        with urllib.request.urlopen("https://index.commoncrawl.org/collinfo.json", timeout=20) as r:
            _latest_crawl.update(id=json.load(r)[0]["id"], at=time.time())
    except Exception:
        _latest_crawl["id"] = _latest_crawl["id"] or "CC-MAIN-2026-43"
    return _latest_crawl["id"]

def defaults():
    return {"sources": {"commoncrawl": True, "snowball": True, "urlscan": False},
            "urlscan_key": os.path.exists(os.path.join(RESEARCH, ".env")),
            "crawl": latest_crawl(), "langs": ["ind", "tha", "vie", "msa"], "lang_choices": LANG_CHOICES,
            "tld": "in", "max_domains": 400, "per_brand": 60, "new_only": True, "capture": True,
            "since": time.strftime("%Y-%m-%d"), "recheck_issues": False}

def verify_busy():
    return os.path.exists(os.path.join(RESEARCH, ".verify.lock"))

def set_status(**kw):
    with state_lock:
        status.update(kw)

def log(line):
    with state_lock:
        status["log"] = (status["log"] + [line])[-200:]
    with open(os.path.join(RESEARCH, "server_run.log"), "a", encoding="utf-8") as f:
        f.write(line + "\n")

def run_step(name, cmd, parse=None):
    set_status(step=name, done=0, total=0)
    log(f"== {name}: {' '.join(cmd[1:])}")
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUNBUFFERED="1")
    p = subprocess.Popen(cmd, cwd=RESEARCH, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace", env=env)
    for line in p.stdout:
        line = line.rstrip()
        if not line: continue
        log(line)
        if parse: parse(line)
    p.wait()
    if p.returncode != 0:
        raise RuntimeError(f"{name} failed (exit {p.returncode}) — see research/server_run.log")

def progress_counter(line):
    m = re.match(r"\[(\d+)/(\d+)\]", line)
    if m: set_status(done=int(m.group(1)), total=int(m.group(2)))
    m = re.match(r"(\d+) to verify", line)
    if m: set_status(done=0, total=int(m.group(1)))

RUNS = os.path.join(RESEARCH, "runs.json")
ISSUE_PREFIXES = ("Down", "error")

def group_of(verdict):
    if verdict == "CONFIRMED hacked": return "confirmed"
    if verdict.startswith("Was hacked") or verdict.startswith("Blocked by ISP"): return "was_hacked"
    if verdict == "Review": return "review"
    if verdict.startswith("Down"): return "issues"
    return "not_lead"

def save_run(report):
    runs = load_runs()
    runs = [r for r in runs if r.get("id") != report["id"]] + [report]
    json.dump(runs, open(RUNS, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    with open(os.path.join(PREVIEW, "runs.js"), "w", encoding="utf-8") as f:   # for file mode too
        f.write("// generated by server.py\nwindow.RUNS = "); json.dump(runs, f, ensure_ascii=False); f.write(";\n")

def load_runs():
    try: return json.load(open(RUNS, encoding="utf-8"))
    except Exception: return []

def job(params):
    py = sys.executable
    t0 = time.time()
    report = {"id": time.strftime("%Y%m%d-%H%M%S"), "started": time.strftime("%Y-%m-%d %H:%M:%S"), "finished": None, "duration_s": None,
              "params": params, "status": "running", "error": None,
              "sources": {}, "looked_at": {}, "suspects": 0, "skipped_old": 0, "skipped_known": 0, "rechecked": 0,
              "verified": 0, "errors": 0, "counts": {}, "india_counts": {}, "domains": {}}
    def parse(line):
        m = re.search(r"(\d+) foreign-language \.(\w+) pages", line)
        if m: report["looked_at"]["commoncrawl_pages"] = int(m.group(1))
        m = re.search(r"(\d+) domains, reading titles for (\d+)", line)
        if m: report["looked_at"]["commoncrawl_domains"] = int(m.group(1)); report["sources"]["commoncrawl"] = int(m.group(2))
        m = re.search(r"(\d+) brands from", line)
        if m: report["looked_at"]["snowball_brands"] = int(m.group(1))
        m = re.search(r"candidates_snowball\.json: (\d+) new domains", line)
        if m: report["sources"]["snowball"] = int(m.group(1))
        m = re.search(r"(\d+) to verify \((\d+) skipped", line)
        if m: report["skipped_known"] = int(m.group(2))
        if re.match(r"\[\d+/\d+\] error:", line): report["errors"] += 1
        progress_counter(line)
    try:
        set_status(running=True, error=None, started=report["started"], finished=None, log=[], params=params, summary=None, run_id=report["id"])
        save_run(report)
        before = {r["domain"]: r for r in load_findings()}
        files = []
        if params["sources"].get("commoncrawl"):
            run_step("Common Crawl search", [py, "collect_commoncrawl.py", params["crawl"], str(params["max_domains"]),
                                             "--langs=" + ",".join(params["langs"]), "--tld=" + params["tld"]], parse)
            files.append("candidates_cc.json")
        if params["sources"].get("snowball"):
            run_step("Snowball from spam brands", [py, "snowball.py", str(params["per_brand"])], parse)
            files.append("candidates_snowball.json")
        if not files and not params["recheck_issues"]:
            raise RuntimeError("No source selected")
        merged = []
        for fn in files:
            merged += json.load(open(os.path.join(RESEARCH, fn), encoding="utf-8"))
        # "since" date: only suspects first seen on/after this date
        if params["since"]:
            keep = [c for c in merged if (c.get("scan_time") or "")[:10] >= params["since"]]
            report["skipped_old"] = len(merged) - len(keep); merged = keep
        allf = os.path.join(RESEARCH, "candidates_all.json")
        allc = json.load(open(allf, encoding="utf-8")) if os.path.exists(allf) else []
        # re-check yesterday's issues: drop down/unreachable results so they are verified again
        if params["recheck_issues"]:
            if verify_busy(): raise RuntimeError("Another verification is already running (research/.verify.lock). Try again when it finishes.")
            F = load_findings(); issues = {r["domain"] for r in F if r["verdict"].startswith(ISSUE_PREFIXES)}
            byd = {c["domain"]: c for c in allc}
            merged += [byd[d] for d in issues if d in byd and d not in {c["domain"] for c in merged}]
            json.dump([r for r in F if r["domain"] not in issues], open(os.path.join(RESEARCH, "findings.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
            report["rechecked"] = len(issues)
        json.dump(merged, open(os.path.join(RESEARCH, "candidates_new.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        known = {c["domain"] for c in allc}
        allc += [c for c in merged if c["domain"] not in known]
        json.dump(allc, open(allf, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        report["suspects"] = len({c["domain"] for c in merged})
        log(f"{report['suspects']} suspects ({report['skipped_old']} older than {params['since'] or '-'} skipped, {report['rechecked']} issues re-checked)")
        save_run(report)
        if verify_busy():
            raise RuntimeError("Another verification is already running (research/.verify.lock). Try again when it finishes.")
        if merged:
            run_step("Verify (4 gates)", [py, "verify.py", "candidates_new.json"] + (["--new-only"] if params["new_only"] else []), parse)
        if params["capture"]:
            run_step("Screenshots (Indian sites)", [py, "capture.py"])
        after = load_findings()
        mine = {c["domain"] for c in merged}
        new = [r for r in after if r["domain"] in mine and (r["domain"] not in before or before[r["domain"]].get("checked") != r.get("checked") or r["domain"] not in before)]
        report["verified"] = len(new)
        for r in new:
            g = group_of(r["verdict"])
            report["counts"][g] = report["counts"].get(g, 0) + 1
            if r["india"]: report["india_counts"][g] = report["india_counts"].get(g, 0) + 1
            report["domains"].setdefault(g, []).append({"domain": r["domain"], "india": r["india"], "verdict": r["verdict"]})
        report["status"] = "done"
        summary = {"new_sites": len(new), "new_india_confirmed": sorted(x["domain"] for x in report["domains"].get("confirmed", []) if x["india"]),
                   "new_india_was_hacked": report["india_counts"].get("was_hacked", 0), "total_sites": len(after), "run_id": report["id"]}
        set_status(summary=summary, step="Done")
        log(f"Done: {json.dumps(summary)}")
    except Exception as e:
        report["status"] = "stopped"; report["error"] = str(e)
        set_status(error=str(e), step="Stopped")
        log(f"ERROR: {e}")
    finally:
        report["finished"] = time.strftime("%Y-%m-%d %H:%M:%S"); report["duration_s"] = round(time.time() - t0)
        save_run(report)
        set_status(running=False, finished=report["finished"])

# ---------- single-site check (research/check_site.py) ----------
check_lock = threading.Lock()
check = {"running": False, "target": None, "domain": None, "step": "", "log": [], "started": None, "finished": None, "error": None, "result": None, "queue": []}

def check_job(target):
    with check_lock: check.update(running=True, target=target, domain=None, step="Starting", log=[], started=time.strftime("%Y-%m-%d %H:%M:%S"), finished=None, error=None, result=None)
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUNBUFFERED="1")
    try:
        pr = subprocess.Popen([sys.executable, "check_site.py", target], cwd=RESEARCH, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace", env=env)
        for line in pr.stdout:
            line = line.rstrip()
            if not line: continue
            with check_lock:
                check["log"] = (check["log"] + [line])[-60:]
                if line.startswith("STEP "): check["step"] = line[5:]
                if line.startswith("RESULT "):
                    parts = [x.strip() for x in line[7:].split("|")]
                    check.update(domain=parts[0], result=parts[1] if len(parts) > 1 else None)
        pr.wait()
        if pr.returncode != 0:
            tail = [l for l in check["log"] if l.strip()][-1:] or ["check failed"]
            raise RuntimeError(tail[0])
        with check_lock: check["step"] = "Done"
    except Exception as e:
        with check_lock: check.update(error=str(e), step="Stopped")
    finally:
        nxt = None
        with check_lock:
            check.update(running=False, finished=time.strftime("%Y-%m-%d %H:%M:%S"))
            if check["queue"]:                       # start the next website that was waiting
                nxt = check["queue"].pop(0)
                check.update(running=True, target=nxt, domain=None, step="Starting", log=[], error=None, result=None)
        if nxt: threading.Thread(target=check_job, args=(nxt,), daemon=True).start()

def load_checks():
    out, folder = [], os.path.join(RESEARCH, "checks")
    if os.path.isdir(folder):
        for fn in os.listdir(folder):
            if fn.endswith(".json"):
                try: out.append(json.load(open(os.path.join(folder, fn), encoding="utf-8")))
                except Exception: pass
    return sorted(out, key=lambda r: r.get("check_time", ""), reverse=True)

def load_findings():
    try: return json.load(open(os.path.join(RESEARCH, "findings.json"), encoding="utf-8"))
    except Exception: return []

def validate(body):
    d = defaults()
    p = {"sources": {k: bool(body.get("sources", {}).get(k, v)) for k, v in d["sources"].items()},
         "crawl": str(body.get("crawl") or d["crawl"]), "langs": [l for l in body.get("langs", d["langs"]) if l in LANG_CHOICES],
         "tld": str(body.get("tld") or "in").lower().strip("."), "max_domains": int(body.get("max_domains", 400)),
         "per_brand": int(body.get("per_brand", 60)), "new_only": bool(body.get("new_only", True)), "capture": bool(body.get("capture", True)),
         "since": str(body.get("since") or ""), "recheck_issues": bool(body.get("recheck_issues", False))}
    errs = []
    if not re.fullmatch(r"CC-MAIN-\d{4}-\d{2}", p["crawl"]): errs.append("Crawl must look like CC-MAIN-2026-43")
    if not p["langs"] and p["sources"]["commoncrawl"]: errs.append("Pick at least one language")
    if not re.fullmatch(r"[a-z]{2,10}", p["tld"]): errs.append("Domain ending must be letters, e.g. in")
    if not 1 <= p["max_domains"] <= 3000: errs.append("Max domains must be 1–3000")
    if not 1 <= p["per_brand"] <= 200: errs.append("Sites per brand must be 1–200")
    if not (p["sources"]["commoncrawl"] or p["sources"]["snowball"] or p["recheck_issues"]): errs.append("Pick at least one source")
    if p["since"] and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", p["since"]): errs.append("Since must be a date like 2026-11-22")
    if p["sources"]["urlscan"] and not d["urlscan_key"]: errs.append("urlscan needs a free API key in research/.env")
    return p, errs

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=PREVIEW, **kw)

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, fmt, *args):
        pass  # keep the console quiet

    def send_json(self, obj, code=200):
        data = json.dumps(obj).encode()
        self.send_response(code); self.send_header("Content-Type", "application/json"); self.send_header("Content-Length", str(len(data)))
        self.end_headers(); self.wfile.write(data)

    def do_GET(self):
        if self.path.startswith("/api/defaults"): return self.send_json(defaults())
        if self.path.startswith("/api/runs"): return self.send_json(load_runs())
        if self.path.startswith("/api/check-status"):
            with check_lock: return self.send_json(dict(check))
        if self.path.startswith("/api/checks"): return self.send_json(load_checks())
        if self.path.startswith("/api/status"):
            with state_lock: s = dict(status)
            s["verify_busy"] = verify_busy() and not s["running"]
            return self.send_json(s)
        if self.path.startswith("/api/"): return self.send_json({"error": "not found"}, 404)
        return super().do_GET()

    def do_POST(self):
        if not (self.path.startswith("/api/search") or self.path.startswith("/api/check")): return self.send_json({"error": "not found"}, 404)
        if self.headers.get("Origin") not in (None, f"http://{HOST}:{PORT}", f"http://localhost:{PORT}"):
            return self.send_json({"error": "forbidden origin"}, 403)       # block other websites from starting runs
        if self.path.startswith("/api/check"):
            try: body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0) or 0)) or b"{}")
            except Exception: return self.send_json({"error": "bad JSON"}, 400)
            target = str(body.get("target") or "").strip()
            if not re.fullmatch(r"(https?://)?[A-Za-z0-9.-]+\.[A-Za-z]{2,}(/[^\s]*)?", target) or len(target) > 300:
                return self.send_json({"error": "Type a website like example.in or https://example.in/page"}, 400)
            with check_lock:
                if check["running"]:
                    if target in check["queue"] or target == check["target"]:
                        return self.send_json({"ok": True, "queued": True, "position": (check["queue"].index(target) + 1) if target in check["queue"] else 0})
                    if len(check["queue"]) >= 20: return self.send_json({"error": "Queue is full (20 websites)"}, 429)
                    check["queue"].append(target)
                    return self.send_json({"ok": True, "queued": True, "position": len(check["queue"])})
                check.update(running=True, target=target, domain=None, step="Starting", log=[], error=None, result=None)   # visible at once
            threading.Thread(target=check_job, args=(target,), daemon=True).start()
            return self.send_json({"ok": True, "target": target})
        try:
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0) or 0)) or b"{}")
        except Exception:
            return self.send_json({"error": "bad JSON"}, 400)
        with state_lock: running = status["running"]
        if running or verify_busy():
            return self.send_json({"error": "A search is already running"}, 409)
        try: params, errs = validate(body)
        except (TypeError, ValueError): return self.send_json({"error": "bad values"}, 400)
        if errs: return self.send_json({"error": "; ".join(errs)}, 400)
        threading.Thread(target=job, args=(params,), daemon=True).start()
        return self.send_json({"ok": True, "params": params})

if __name__ == "__main__":
    srv = ThreadingHTTPServer((HOST, PORT), Handler)
    print(f"SiteWatch India running at http://{HOST}:{PORT}  (Ctrl+C to stop)")
    try: srv.serve_forever()
    except KeyboardInterrupt: pass
